CREATE TABLE `nascar`.`practice_results` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    `practice_id` BIGINT UNSIGNED NOT NULL,
    `car_driver_id` BIGINT UNSIGNED NOT NULL,
    `finish_position` INT UNSIGNED NOT NULL,
    `best_speed` DECIMAL(8,3) UNSIGNED NULL,
    `best_time` TIME(3) NULL,
    `total_laps` INT UNSIGNED NULL,
    `5_lap_average_time` TIME(3) NULL,
    `10_lap_average_time` TIME(3) NULL,
    `20_lap_average_time` TIME(3) NULL,
    `25_lap_average_time` TIME(3) NULL,
    `30_lap_average_time` TIME(3) NULL,
    `10_lap_average_speed` DECIMAL(8,3) UNSIGNED NULL,
    `10_lap_start` INT UNSIGNED NULL,
    `10_lap_end` INT UNSIGNED NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `deleted_at` TIMESTAMP NULL DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
