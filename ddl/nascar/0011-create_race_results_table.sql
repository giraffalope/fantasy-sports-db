CREATE TABLE `race_results` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    `race_id` BIGINT UNSIGNED NOT NULL,
    `car_driver_id` BIGINT UNSIGNED NOT NULL,
    `start_position` INT UNSIGNED DEFAULT NULL,
    `finish_position` INT UNSIGNED DEFAULT NULL,
    `best_position` INT UNSIGNED DEFAULT NULL,
    `worst_position` INT UNSIGNED DEFAULT NULL,
    `average_position` INT UNSIGNED DEFAULT NULL,
    `pass_diff` INT SIGNED DEFAULT NULL,
    `green_flag_passes` INT UNSIGNED DEFAULT NULL,
    `green_flag_times_passed` INT UNSIGNED DEFAULT NULL,
    `quality_passes` INT UNSIGNED DEFAULT NULL,
    `quality_passes_pct` DECIMAL(8,3) UNSIGNED DEFAULT NULL,
    `total_fastest_laps` INT UNSIGNED DEFAULT NULL,
    `total_top_15_laps` INT UNSIGNED DEFAULT NULL,
    `total_top_15_laps_pct` DECIMAL(8,3) UNSIGNED DEFAULT NULL,
    `total_laps_led` INT UNSIGNED DEFAULT NULL,
    `total_laps_led_pct` DECIMAL(8,3) UNSIGNED DEFAULT NULL,
    `total_laps_completed` INT UNSIGNED DEFAULT NULL,
    `driver_rating` DECIMAL(8,3) UNSIGNED DEFAULT NULL,
    `car_status` VARCHAR(255) DEFAULT NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `deleted_at` TIMESTAMP NULL DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
